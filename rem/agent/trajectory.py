"""Runtime trajectory representation for AI-agent execution.

REM evaluates agent behaviour during execution, so the trajectory is the central
runtime object: an ordered sequence of steps, each capturing what the agent saw,
what it produced, what it did, and what REM decided about it.

The frozen pipeline begins with *provenance labeling*, so each content item
carries a provenance label slot. The labeling **rule** is not frozen anywhere
and is therefore unresolved; this module provides the representation only and
assigns nothing.

This module is a data model: no mathematics, no scoring.
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, Iterator, List, Mapping, Optional, Sequence

__all__ = [
    "Provenance",
    "AgentState",
    "ContentItem",
    "ToolCall",
    "Observation",
    "Evidence",
    "TrajectoryStep",
    "Trajectory",
    "new_trajectory_id",
]


def _utcnow() -> datetime:
    return datetime.now(timezone.utc)


def new_trajectory_id() -> str:
    """Return a fresh trajectory identifier."""
    return f"traj-{uuid.uuid4().hex[:16]}"


class Provenance(str, Enum):
    """Origin of a piece of content reaching the agent.

    The frozen pipeline's first stage is provenance labeling. These are the
    representation's categories; the *rule* that assigns them is not frozen and
    is not implemented here.

    Members:
        UNLABELLED: No provenance assigned yet. The default, because assigning
            one requires the unresolved labeling rule.
        SYSTEM: Operator-authored system instruction.
        USER: The principal's own instruction.
        TOOL_OUTPUT: Content returned by a tool — the surface on which indirect
            prompt injection arrives.
        MODEL: Content generated by the agent's own model.
    """

    UNLABELLED = "unlabelled"
    SYSTEM = "system"
    USER = "user"
    TOOL_OUTPUT = "tool_output"
    MODEL = "model"


class AgentState(str, Enum):
    """Observed lifecycle state of the agent at a step boundary.

    These are *observed execution states* recorded by instrumentation. They are
    not latent states of any model; the frozen design contains no latent-variable
    trajectory model, and GRU/LSTM/Transformer trajectory models are forbidden
    reintroductions.
    """

    INITIALISED = "initialised"
    PLANNING = "planning"
    TOOL_SELECTION = "tool_selection"
    TOOL_EXECUTION = "tool_execution"
    OBSERVING = "observing"
    RESPONDING = "responding"
    TERMINATED = "terminated"
    HALTED_BY_REM = "halted_by_rem"


@dataclass(frozen=True)
class ContentItem:
    """A piece of content with its provenance label.

    Attributes:
        content: The content itself, carried verbatim. Adversarial content must
            survive unmodified so the detector can see it; sanitising at the
            data layer would hide the attack from REM.
        provenance: Origin label, ``UNLABELLED`` until the labeling rule exists.
        origin: Free-text detail (tool name, document id).
    """

    content: str
    provenance: Provenance = Provenance.UNLABELLED
    origin: str = ""


@dataclass(frozen=True)
class ToolCall:
    """A tool invocation requested by the agent.

    Attributes:
        name: Tool identifier as exposed to the agent.
        arguments: Arguments the agent supplied, unmodified.
        call_id: Identifier correlating the call with its observation.
    """

    name: str
    arguments: Mapping[str, Any] = field(default_factory=dict)
    call_id: str = field(default_factory=lambda: uuid.uuid4().hex[:12])


@dataclass(frozen=True)
class Observation:
    """Result returned to the agent after an action.

    Attributes:
        content: The observation payload as the agent would receive it.
        source: Where it came from (tool name, environment, user).
        provenance: Origin label for the payload.
        call_id: Correlates with :attr:`ToolCall.call_id` when applicable.
        error: Error text when the action failed, else ``None``.
    """

    content: Any
    source: str
    provenance: Provenance = Provenance.UNLABELLED
    call_id: Optional[str] = None
    error: Optional[str] = None

    @property
    def failed(self) -> bool:
        """Whether the action produced an error."""
        return self.error is not None


@dataclass(frozen=True)
class Evidence:
    """One named evidence item extracted by the Input & Context layer (L1).

    The frozen pipeline's second stage is "context / behavioral / action
    evidence". Evidence records *that something was observed*; it carries no
    weight or severity, because combining evidence into a score is the job of
    the ridge logistic regression, whose coefficients are fitted. A severity
    field here would be an invented weight entering through the data model.

    Attributes:
        name: Evidence identifier.
        value: The extracted value.
        producer: Component that emitted it.
        detail: Human-readable justification, for the audit record.
    """

    name: str
    value: Any
    producer: str
    detail: str = ""


@dataclass
class TrajectoryStep:
    """One step of agent execution, with REM's assessment of it.

    REM-produced fields start empty and are populated as the step is evaluated.

    Attributes:
        step_index: Zero-based position within the trajectory.
        timestamp: When the step was recorded (UTC).
        agent_state: Observed lifecycle state during this step.
        context: Context available to the agent, with provenance labels.
        prompt: The input presented to the model at this step.
        model_output: Raw model output for this step.
        tool_call: Tool the agent requested, if any.
        action: Normalised description of what the agent did.
        observation: What came back after the action.
        previous_state: Observed state before the transition into this step.
        current_state: Observed state after the transition.
        evidence: Evidence items extracted by L1.
        consequence_tier: ``k_t`` for this step. ``None`` until the unresolved
            consequence-tier definition is supplied.
        decision: REM verdict, populated by L4.
        mitigation: Mitigation outcome, populated by L5.
        metadata: Free-form provenance (model version, seed, environment).
    """

    step_index: int
    agent_state: AgentState = AgentState.INITIALISED
    timestamp: datetime = field(default_factory=_utcnow)
    context: Sequence[ContentItem] = field(default_factory=tuple)
    prompt: Optional[str] = None
    model_output: Optional[str] = None
    tool_call: Optional[ToolCall] = None
    action: Optional[str] = None
    observation: Optional[Observation] = None
    previous_state: Optional[AgentState] = None
    current_state: Optional[AgentState] = None
    evidence: List[Evidence] = field(default_factory=list)
    consequence_tier: Optional[Any] = None
    decision: Optional[Any] = None       # rem.core.results.Decision
    mitigation: Optional[Any] = None     # rem.core.results.MitigationOutcome
    metadata: Dict[str, Any] = field(default_factory=dict)

    @property
    def tool_arguments(self) -> Mapping[str, Any]:
        """Arguments of the requested tool call, or an empty mapping."""
        return self.tool_call.arguments if self.tool_call else {}

    def add_evidence(self, item: Evidence) -> None:
        """Attach an evidence item produced by the Input & Context layer."""
        self.evidence.append(item)

    def find_evidence(self, name: str) -> Optional[Evidence]:
        """Return the first evidence item with ``name``, if present."""
        return next((e for e in self.evidence if e.name == name), None)


@dataclass
class Trajectory:
    """An ordered sequence of agent execution steps.

    Attributes:
        trajectory_id: Stable identifier used across logs and audit records.
        steps: Steps in execution order.
        created_at: Creation time (UTC).
        metadata: Run-level provenance (experiment ID, config, versions).
    """

    trajectory_id: str = field(default_factory=new_trajectory_id)
    steps: List[TrajectoryStep] = field(default_factory=list)
    created_at: datetime = field(default_factory=_utcnow)
    metadata: Dict[str, Any] = field(default_factory=dict)

    def append(self, step: TrajectoryStep) -> TrajectoryStep:
        """Append ``step``, wiring its state transition to the previous step.

        Args:
            step: The step to append.

        Returns:
            The appended step.

        Raises:
            ValueError: If ``step.step_index`` does not continue the sequence.
        """
        expected = len(self.steps)
        if step.step_index != expected:
            raise ValueError(
                f"Trajectory {self.trajectory_id}: expected step_index "
                f"{expected}, got {step.step_index}."
            )
        if step.previous_state is None and self.steps:
            step.previous_state = self.steps[-1].current_state
        if step.current_state is None:
            step.current_state = step.agent_state
        self.steps.append(step)
        return step

    def new_step(self, **kwargs: Any) -> TrajectoryStep:
        """Construct and append a step with the next index."""
        return self.append(TrajectoryStep(step_index=len(self.steps), **kwargs))

    def transitions(self) -> List[tuple[AgentState, AgentState]]:
        """Return observed ``(previous_state, current_state)`` pairs.

        The raw observed-transition sequence. It implies no transition
        probabilities and is not itself a model.
        """
        pairs: List[tuple[AgentState, AgentState]] = []
        for step in self.steps:
            if step.previous_state is not None and step.current_state is not None:
                pairs.append((step.previous_state, step.current_state))
        return pairs

    def tool_calls(self) -> List[ToolCall]:
        """Return every tool call in execution order."""
        return [s.tool_call for s in self.steps if s.tool_call is not None]

    def prefix(self, upto: int) -> "Trajectory":
        """Return the trajectory truncated to the first ``upto`` steps.

        Runtime evaluation is causal: a component scoring step *t* must not see
        steps at or after *t*. Components receive a prefix rather than the whole
        trajectory so this is structural rather than a matter of discipline.
        """
        return Trajectory(
            trajectory_id=self.trajectory_id,
            steps=self.steps[:upto],
            created_at=self.created_at,
            metadata=dict(self.metadata),
        )

    def __len__(self) -> int:
        return len(self.steps)

    def __iter__(self) -> Iterator[TrajectoryStep]:
        return iter(self.steps)
