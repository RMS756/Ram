"""Tables of the repair study, generated from saved outputs only (results/*.json). No replay, no model call.

usage: python3 experiments/repair_study/rs_tables.py  ->  REM_REPAIR_STUDY_2026_11_17/03_RESULTS_TABLES.md
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
D = ROOT / "REM_REPAIR_STUDY_2026_11_17"
r = json.loads((D / "results" / "results.json").read_text())
diag = json.loads((D / "results" / "defects_after.json").read_text())
resid = json.loads((D / "results" / "residual_stage_diagnostics.json").read_text())
ARMS = ["REM10", "PG", "G3", "GV", "HV", "G3_math", "GV_math", "HV_math"]
POPS = [("primary_S1", "Primary, S1"), ("primary_S2", "Primary, S2"), ("dev2", "Second population, S1 models")]
L = ["# Repair study of 17 November 2026: results tables", "",
     "Generated by `experiments/repair_study/rs_tables.py` from `results/results.json`, `results/defects_after.json` and "
     "`results/residual_stage_diagnostics.json`. Status: exploratory development evidence (offline recorded-trace replay; no live agent; "
     "no model call). Baselines are stored replays; the repaired arms were replayed after the protocol commit `f81f6b3`.", ""]


def pct(x):
    return f"{100 * x:+.2f}"


for key, title in POPS:
    P = r["populations"][key]
    L += [f"## {title}: {P['n_attacked']} attacked, {P['n_benign']} benign episodes", "",
          "| Arm | Successful attacks | Benign completed | Completed under attack | All tasks completed | Attack-labelled calls released | Restricted calls of benign episodes released |",
          "|---|---:|---:|---:|---:|---:|---:|"]
    for a in ARMS:
        m = P["arms"][a]
        L.append(f"| {a} | {m['attacks_successful']} / {m['n_attacked']} | {m['benign_completed']} / {m['n_benign']} | {m['tasks_completed_under_attack']} | "
                 f"{m['all_tasks_completed']} / {m['n_attacked'] + m['n_benign']} | {m['attack_labelled_calls_released']} / {m['attack_labelled_calls_n']} | "
                 f"{m['legit_calls_released_benign']} / {m['legit_calls_n']} |")
    L += ["", "Paired grouped bootstrap (2,000 resamples, seed 20261027; percentage points; user task as unit for completion, attacker objective for attacks). "
          "Descriptive intervals (16 and 9 groups).", "",
          "| Contrast | All-task completion [95% interval] | Benign completion [95% interval] | Attack success | Tasks gained / lost | Attacks gained / lost |",
          "|---|---|---|---|---|---|"]
    for k, c in P["contrasts"].items():
        t, b, s = c["task_completion_all"], c.get("task_completion_benign"), c["attack_success"]
        L.append(f"| {k} | {pct(t[0])} [{pct(t[1])}, {pct(t[2])}] | " + (f"{pct(b[0])} [{pct(b[1])}, {pct(b[2])}]" if b else "—") +
                 f" | {pct(s[0])} [{pct(s[1])}, {pct(s[2])}] | {c['tasks_gained_lost'][0]} / {c['tasks_gained_lost'][1]} | "
                 f"{c['attacks_gained_lost'][0]} / {c['attacks_gained_lost'][1]} |")
    L += ["", "Stage accounting of restricted calls (every proposed restricted call, all episodes):", "",
          "| Arm | Attack-labelled: stopped at front | Not attack-labelled: front | predicate (D2) | amount mismatch | amount unresolved | released after the decision rule | withheld by the decision rule |",
          "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for a in ["GV_math", "HV_math", "G3_math"]:
        s = P["restricted_call_stages"][a]
        rel = s.get("not_attack_labelled|rule_released", 0)
        wr = sum(v for k2, v in s.items() if k2.startswith("not_attack_labelled|rule_withheld"))
        pr = sum(v for k2, v in s.items() if k2.startswith("not_attack_labelled|predicate"))
        L.append(f"| {a} | {s.get('attack_labelled|front_blocked', 0)} | {s.get('not_attack_labelled|front_blocked', 0)} | {pr} | "
                 f"{s.get('not_attack_labelled|amount_mismatch', 0)} | {s.get('not_attack_labelled|amount_unresolved', 0)} | {rel} | {wr} |")
    other = {a: {k2: v for k2, v in P["restricted_call_stages"][a].items() if k2.startswith("attack_labelled") and k2 != "attack_labelled|front_blocked"}
             for a in ["GV_math", "HV_math", "G3_math"]}
    L += ["", "Attack-labelled restricted calls decided anywhere other than the front: " +
          ("none, for all three repaired arms. No benchmark-labelled attack call reached the amount verifier or the decision rule in these recordings."
           if not any(other.values()) else json.dumps(other)), "",
          "Episodes whose outcome differs from the unrepaired arm:", "", "| Comparison | Episodes | By user task |", "|---|---:|---|"]
    for k, v in P["outcome_changes"].items():
        L.append(f"| {k} | {v['episodes_with_different_outcome']} | " + (", ".join(f"{u}: {n}" for u, n in sorted(v["by_user_task"].items())) or "—") + " |")
    L.append("")
L += ["## Probe (reformatted attacker identifier, 2,645 attacked episodes)", "", "| Arm | Successful attacks | Replay errors |", "|---|---:|---:|"]
for a in ARMS:
    v = r["probe_reformatted_identifier"]["arms"][a]
    L.append(f"| {a} | {v['attacks']} | {v['replay_errors']} |")
L += ["", "## Fixtures (43 author-written regression pairs)", "", "| Set | Arm | Legitimate released | Unsafe released | Pairs correct |", "|---|---|---:|---:|---:|"]
for s, v in r["fixtures_baselines_stored"].items():
    for a in ["G3", "GV", "HV"]:
        x = v[a]
        L.append(f"| {s} | {a} (stored) | {x['legitimate_released']} / {x['n']} | {x['unsafe_released']} | {x['pairs_correct']} |")
    for a in ["G3_math", "GV_math", "HV_math"]:
        x = r["fixtures"][s][a]
        L.append(f"| {s} | {a} | {x['legitimate_released']} / {x['n']} | {x['unsafe_released']} | {x['pairs_correct']} |")
tot = {a: sum(r["fixtures"][s][a]["pairs_correct"] for s in r["fixtures"]) for a in ["G3_math", "GV_math", "HV_math"]}
tot.update({a: sum(r["fixtures_baselines_stored"][s][a]["pairs_correct"] for s in r["fixtures_baselines_stored"]) for a in ["G3", "GV", "HV"]})
L += ["", "Pairs correct of 43: " + ", ".join(f"{a} {n}" for a, n in tot.items()) + ".", ""]
L += ["## C1 and C2 after the repair (proposed calls; fresh guard per call)", "", "| Case | Arm | Variant | Correct amount released | Wrong amounts released |", "|---|---|---|---|---|"]
from collections import defaultdict
g = defaultdict(lambda: {"ok": [], "bad": []})
for x in diag["rows"]:
    k = (x["case"], x["arm"], x["variant"])
    if x["expected"] == "release" and x["released"]:
        g[k]["ok"].append(x["amount"])
    if x["expected"] == "withhold" and x["released"]:
        g[k]["bad"].append(x["amount"])
    g[k]
for (case, arm, var), v in g.items():
    L.append(f"| {case} | {arm} | {var} | {', '.join(map(str, v['ok'])) or 'none'} | {', '.join(map(str, v['bad'])) or 'none'} |")
L += ["", "## Residual-stage diagnostics (hand-written; not an attack-success rate)", "",
      "| Case | Request | Amount (origin) | " + " | ".join(["G3", "GV", "HV", "G3_math", "GV_math", "HV_math"]) + " |", "|---|---|---|" + "---|" * 6]
cases = {c["id"]: c for c in resid["cases"]}
gr = defaultdict(dict)
for x in resid["rows"]:
    gr[(x["case"], x["amount"], x["amount_origin"])][x["arm"]] = ("released" if x["released"] else "withheld") + f" ({x['source']})"
for (case, amt, why), v in gr.items():
    L.append(f"| {case} | {cases[case]['objective']} | {amt} ({why}) | " + " | ".join(v[a] for a in ["G3", "GV", "HV", "G3_math", "GV_math", "HV_math"]) + " |")
L += ["", "R2 (first run) proposed `send_money` for a recurring request; R2b, added after the first run, proposes `schedule_transaction`. Both are kept.", ""]
L += ["## Cohort hashes", "", "| Cohort | Episodes | SHA-256 of sorted identifiers |", "|---|---:|---|"]
for k, v in r["cohorts"].items():
    L.append(f"| {k} | {v['episodes']} | `{v['sha256_sorted_ids']}` |")
(ROOT / "REM_REPAIR_STUDY_2026_11_17" / "03_RESULTS_TABLES.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("written", len(L), "lines")
