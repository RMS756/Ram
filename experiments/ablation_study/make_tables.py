"""Markdown tables generated from REM_ABLATION_STUDY/results/ablation_metrics.json (no hand-typed values)."""
import json
from pathlib import Path

D = Path(__file__).resolve().parents[2] / "REM_ABLATION_STUDY"
M = json.loads((D / "results" / "ablation_metrics.json").read_text())
ARMS = ["B0", "A0", "A1a", "A1b", "A2", "AIC", "A3", "A3P", "A4"]


def ci(v, d=1):
    if not v or v[0] is None or v[0] != v[0]:
        return "n/a"
    return f"{100*v[0]:.{d}f} [{100*v[1]:.{d}f}, {100*v[2]:.{d}f}]"


def prec(v):
    return "n/a" if v is None else "%.3f" % v


def pv(p):
    return "–" if p is None else "%.3g" % p


out = ["<!-- generated by experiments/ablation_study/make_tables.py; do not edit -->"]
for pop, r in M["populations"].items():
    out += ["", f"## {pop}: {r['episodes_valid']} eligible episodes ({r['attacked']} attacked, {r['benign']} benign) of {r['loaded']} loaded", "",
            "### Call level (restricted tools)", "",
            "| Arm | Attack-labelled withheld / calls | Withholding rate % [95% CI] | Benign-episode calls withheld / calls | Benign-call blocking % [95% CI] | Unlabelled calls in attacked episodes withheld / calls | Precision | Median / p95 ms |",
            "|---|---|---|---|---|---|---|---|"]
    for a in ARMS:
        m = r["arms"][a]
        out.append(f"| {a} | {m['attack_labelled_withheld']} / {m['attack_labelled_calls']} | {ci(m['attack_call_withholding_rate'])} | "
                   f"{m['benign_episode_calls_withheld']} / {m['benign_episode_restricted_calls']} | {ci(m['benign_call_blocking_rate'])} | "
                   f"{m['unlabelled_calls_in_attacked_episodes_withheld']} / {m['unlabelled_calls_in_attacked_episodes']} | "
                   f"{prec(m['withhold_precision'])} | {m['latency_full_ms_median']:.3f} / {m['latency_full_ms_p95']:.3f} |")
    out += ["", "### Paired comparison with A0 (arm − A0)", "",
            "| Arm | Δ attack-call withholding pp [95% CI] | Δ benign-call blocking pp [95% CI] | Call verdict changes | Call release changes (class: direction = count) | Δ replay attack outcome pp [95% CI] (NO-ADAPT) | Discordant episodes arm/A0 (McNemar p) | Δ replay benign completion pp [95% CI] (NO-ADAPT) |",
            "|---|---|---|---|---|---|---|---|"]
    for a in ARMS:
        if a == "A0":
            continue
        d = r["paired_vs_A0"][a]
        ch = "; ".join(f"{k.replace('A0_withheld_arm_released', 'released by arm').replace('A0_released_arm_withheld', 'withheld by arm')} = {v}"
                       for k, v in sorted(d["call_release_changes_vs_A0"].items())) or "none"
        p = d["mcnemar_p_attack_outcome"]
        out.append(f"| {a} | {ci(d['d_attack_call_withholding_rate'], 2)} | {ci(d['d_benign_call_blocking_rate'])} | {d['call_verdict_changes_vs_A0']} | {ch} | "
                   f"{ci(d['d_replay_attack_outcome_rate'], 2)} | {d['attack_outcome_discordant_arm_only_A0_only'][0]}/{d['attack_outcome_discordant_arm_only_A0_only'][1]} "
                   f"({pv(p)}) | {ci(d['d_replay_benign_completion_rate'])} |")
    out += ["", "### Replay episode outcomes (NO-ADAPT; not closed-loop ASR or task completion)", "",
            "| Arm | Replay attack outcomes / attacked | Replay tasks completed under attack | Replay benign completed / benign |", "|---|---|---|---|"]
    for a in ARMS:
        m = r["arms"][a]
        out.append(f"| {a} | {m['replay_attack_outcomes']} / {m['episodes_attacked']} | {m['replay_tasks_under_attack']} | {m['replay_benign_completed']} / {m['episodes_benign']} |")
    s = r["shadow_mode"]
    out += ["", f"Shadow mode (A4): verdict agreement with enforced A0 on {s['verdict_agreement_with_enforced']} of {s['calls_compared']} calls; "
            f"episodes with at least one diverging verdict: {s['episodes_with_a_divergence']}; calls executed although the shadow verdict would withhold them: "
            f"{s['calls_executed_while_shadow_verdict_would_withhold']}; attack-labelled calls flagged in shadow: {s['shadow_attack_labelled_calls_flagged']} / {s['shadow_attack_labelled_calls']}."]
out += ["", f"A1b refit: features {M['a1b_refit']['features']}; held-out ROC-AUC {M['a1b_refit']['roc_auc']:.4f}, PR-AUC {M['a1b_refit']['pr_auc']:.4f}.",
        f"Hygiene check: {M['hygiene_check']['segments_changed_by_hygiene']} of {M['hygiene_check']['tool_output_segments']} tool-output segments would be changed."]
(D / "results" / "tables.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
