"""Mechanism-activity summary of the SCRIPTED integration pilot (diagnostic; never an ASR/utility estimate).

usage: python3 experiments/rem_vs_melon/summarize_pilot.py <pilot_dir> <out.md>
"""
import json
import sys

import numpy as np

rows = [json.loads(l) for l in open(sys.argv[1] + "/episodes.jsonl")]
out = ["<!-- generated by experiments/rem_vs_melon/summarize_pilot.py; SCRIPTED AGENT + STAND-IN EMBEDDINGS: "
       "integration diagnostics only, NOT attack-success or utility results -->", "",
       "| Arm | Episodes (attacked / benign) | Errors | Agent LLM calls | MELON masked re-executions | Embedding calls | "
       "REM decisions | REM refusals (attacked / benign) | MELON flags (attacked / benign) | Scripted-agent injection goal reached (attacked) |",
       "|---|---|---|---|---|---|---|---|---|---|"]
summary = {}
for arm in ("D0_NO_DEFENSE", "D1_REM", "D2_MELON"):
    R = [r for r in rows if r["arm"] == arm]
    A = [r for r in R if r["injection_task"]]
    B = [r for r in R if not r["injection_task"]]
    lat = [x for r in R for x in r["rem_latency_ms"]]
    s = {"episodes": len(R), "attacked": len(A), "benign": len(B), "errors": sum(r["error"] is not None for r in R),
         "agent_calls": sum(r["llm_calls_agent"] for r in R), "masked_calls": sum(r["llm_calls_melon_masked"] for r in R),
         "embedding_calls": sum(r["embedding_calls"] for r in R), "rem_decisions": len(lat),
         "rem_refusals_att": sum(r["calls_refused_by_rem"] for r in A), "rem_refusals_ben": sum(r["calls_refused_by_rem"] for r in B),
         "melon_flags_att": sum(bool(r["melon_flagged"]) for r in A), "melon_flags_ben": sum(bool(r["melon_flagged"]) for r in B),
         "scripted_goal_reached": sum(r["security"] for r in A),
         "rem_latency_ms_median": float(np.median(lat)) if lat else None,
         "rem_latency_ms_p95": float(np.percentile(lat, 95)) if lat else None}
    summary[arm] = s
    out.append(f"| {arm} | {s['attacked']} / {s['benign']} | {s['errors']} | {s['agent_calls']} | {s['masked_calls']} | "
               f"{s['embedding_calls']} | {s['rem_decisions']} | {s['rem_refusals_att']} / {s['rem_refusals_ben']} | "
               f"{s['melon_flags_att']} / {s['melon_flags_ben']} | {s['scripted_goal_reached']} / {s['attacked']} |")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
json.dump(summary, open(sys.argv[2].replace(".md", ".json"), "w"), indent=1)
print("\n".join(out))
print({k: (v["rem_latency_ms_median"], v["rem_latency_ms_p95"]) for k, v in summary.items()})
