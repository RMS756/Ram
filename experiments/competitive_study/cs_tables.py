"""Generate REM_COMPETITIVE_STUDY_2026_11_16/03_RESULTS_TABLES.md from the saved result files. No number is typed by hand."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
D = ROOT / "REM_COMPETITIVE_STUDY_2026_11_16"
R = json.loads((D / "results" / "results.json").read_text())
R11 = json.loads((D / "results" / "results_section11.json").read_text())
FS = json.loads((D / "results" / "fits_summary.json").read_text())
NAME = {"B0": "No defense", "REM10": "REM v1.0", "REM11": "REM v1.1", "A2": "Rule A2", "PG": "PG: Progent manual policy (replay adaptation)", "G3": "G3 (strict rule)",
        "GV": "**GV: authority and value guard alone**", "L4": "L4", "HV": "HV", "HVx": "HVx (HV rebuilt; equivalence check)", "HVnc": "HVnc (no calibration map)",
        "HV4": "HV4 (four verdicts)", "NP05": "NP05 (NP cutoff, alpha 0.05)", "NP01": "NP01 (NP cutoff, alpha 0.01)", "CRC05": "CRC05 (CRC cutoff, alpha 0.05)",
        "CRC01": "CRC01 (CRC cutoff, alpha 0.01)", "GB": "GB (gradient-boosted trees)", "GVc": "GVc (GV decided by Cedar policies)", "GVp": "GVp (GV plus provenance rule)"}
ARMS = ["B0", "REM10", "REM11", "A2", "PG", "G3", "GV", "L4", "HV", "HVnc", "HV4", "NP05", "NP01", "CRC05", "CRC01", "GB"]
POPS = [("primary_S1", "Primary, S1 (held-out attacker objective)"), ("primary_S2", "Primary, S2 (double holdout)"), ("dev2", "Second population")]
n = lambda x: f"{x:,}"
pct = lambda a, b: f"{100 * a / b:.1f}%"


def iv(v):
    f = lambda x: f"{100 * x:+.2f}"
    return f"{f(v[0])} [{f(v[1])}, {f(v[2])}]"


out = ["# Result tables (generated)", "",
       "Generated by `experiments/competitive_study/cs_tables.py` from `results/results.json`, `results/results_section11.json` and `results/fits_summary.json`. "
       "**Every number is development evidence** from offline recorded-trace replay under NO-ADAPT; no live agent, no model call, no reviewer. Do not edit by hand.", ""]

for k, (pk, title) in enumerate(POPS, 1):
    P = R["populations"][pk]
    na, nb = P["n_attacked"], P["n_benign"]
    out += [f"## Table {k}. {title}", "",
            f"| Arm | Successful attacks / {n(na)} | Benign tasks / {nb} | Tasks under attack / {n(na)} | All tasks / {n(na + nb)} | Legitimate state-changing calls of benign episodes released / withheld | Attack-labelled calls released | Decision time, median / 95th pct (ms) |",
            "|---|---|---|---|---|---|---|---|"]
    for a in ARMS:
        m = P["arms"][a]
        out.append(f"| {NAME[a]} | {m['attacks_successful']} ({pct(m['attacks_successful'], na)}) | {m['benign_completed']} ({pct(m['benign_completed'], nb)}) | "
                   f"{n(m['tasks_completed_under_attack'])} | {n(m['all_tasks_completed'])} ({pct(m['all_tasks_completed'], na + nb)}) | "
                   f"{m['legit_calls_released_benign']} / {m['legit_calls_n'] - m['legit_calls_released_benign']} | {m['attack_labelled_calls_released']} of {m['attack_labelled_calls_n']} | "
                   f"{m['decision_ms_median']:.2f} / {m['decision_ms_p95']:.2f} |")
    out.append("")

out += ["## Table 4. Paired contrasts (first arm minus second arm; percentage points; 95% grouped-bootstrap interval)", "",
        "| Contrast | Evaluation | All-task completion | Benign task completion | Attack success | Tasks gained / lost | Attacks gained / lost | User tasks higher / lower / equal |", "|---|---|---|---|---|---|---|---|"]
KEY = [("GV", "HV"), ("GV", "G3"), ("GV", "PG"), ("GV", "REM10"), ("HV", "PG"), ("HV", "G3"), ("NP05", "HV"), ("NP05", "GV"), ("NP01", "HV"), ("CRC05", "HV"), ("CRC01", "HV"),
       ("GB", "HV"), ("GB", "GV"), ("HVnc", "HV"), ("HV4", "HV"), ("NP05", "PG"), ("CRC05", "PG"), ("GB", "PG")]
for a, b in KEY:
    for pk, title in POPS:
        key = f"{a} minus {b}" if f"{a} minus {b}" in R["populations"][pk]["contrasts"] else None
        if key is None:
            continue
        c = R["populations"][pk]["contrasts"][key]
        u = R["populations"][pk]["per_user_task_difference_counts"][key]
        out.append(f"| {a} − {b} | {title.split(',')[0] if pk != 'primary_S2' else 'Primary'}{', S1' if pk == 'primary_S1' else (', S2' if pk == 'primary_S2' else '')} | {iv(c['task_completion_all'])} | "
                   f"{iv(c['task_completion_benign'])} | {iv(c['attack_success'])} | {c['tasks_gained_lost'][0]} / {c['tasks_gained_lost'][1]} | "
                   f"{c['attacks_gained_lost'][0]} / {c['attacks_gained_lost'][1]} | {u['user_tasks_higher']} / {u['user_tasks_lower']} / {u['user_tasks_equal']} |")
out.append("")

out += ["## Table 5. Where each restricted call was decided (primary S1 and second population; counts of calls)", "",
        "| Arm | Population | Attack-labelled: stopped by the authority front | Attack-labelled: reaching the rule | Other calls: stopped by the front | Other: withheld by a declared predicate (D2) | Other: withheld by the rule | Other: refused by the value constraint | Other: released | Unrestricted calls withheld |",
        "|---|---|---|---|---|---|---|---|---|---|"]
for a in ["GV", "HVx", "HVnc", "HV4", "NP05", "NP01", "CRC05", "CRC01", "GB"]:
    for pk, title in (POPS[0], POPS[2]):
        s = R["populations"][pk]["restricted_call_stages"][a]
        g = lambda *keys: sum(v for k, v in s.items() if any(k == x or k.startswith(x) for x in keys))
        reach = sum(v for k, v in s.items() if k.startswith("attack_labelled|") and "front_blocked" not in k)
        pred = g("not_attack_labelled|predicate_") + (s.get("not_attack_labelled|rule_withheld_escalate", 0) if a in ("HVx", "HVnc", "HV4", "GB") else 0)
        rule = g("not_attack_labelled|rule_withheld_") - (s.get("not_attack_labelled|rule_withheld_escalate", 0) if a in ("HVx", "HVnc", "HV4", "GB") else 0)
        out.append(f"| {a} | {title.split(',')[0]} | {s.get('attack_labelled|front_blocked', 0)} | {reach} | {s.get('not_attack_labelled|front_blocked', 0)} | {pred} | {rule} | "
                   f"{s.get('not_attack_labelled|value_constraint_refused', 0)} | {s.get('not_attack_labelled|rule_released', 0)} | {s.get('unrestricted_withheld', 0)} |")
out += ["", "For the arms that use REM's policy object (HVx, HVnc, HV4, GB) the Escalate verdicts are those forced by the declared predicate D2 (required evidence unavailable); "
        f"HV4's verdicts on calls reaching the rule: {R['HV4_verdicts_on_calls_reaching_the_rule']}.", ""]

fx = R["fixtures"]
out += ["## Table 6. Paired fixtures (43 pairs; regression material, author-written and previously inspected)", "",
        "| Arm | Legitimate calls released / 43 | Unsafe calls released | Pairs correct / 43 | Unsafe fixtures released |", "|---|---|---|---|---|"]
for a in [x for x in ARMS if x != "B0"]:
    L = sum(fx[s][a]["legitimate_released"] for s in fx)
    U = sum(fx[s][a]["unsafe_released"] for s in fx)
    Cc = sum(fx[s][a]["pairs_correct"] for s in fx)
    uns = [x["fixture"] for s in fx for x in fx[s][a]["rows"] if x["unsafe"]]
    out.append(f"| {NAME[a]} | {L} | {U} | {Cc} | {', '.join(uns) if uns else '—'} |")
src = lambda arm, role: dict(sorted(__import__("collections").Counter(x[role + "_source"] for s in fx for x in fx[s][arm]["rows"]).items()))
out += ["", f"Stage that decided the unsafe call, GV: {src('GV', 'unsafe')}; HVx: {src('HVx', 'unsafe')}.",
        f"Stage that decided the legitimate call, GV: {src('GV', 'legitimate')}; HVx: {src('HVx', 'legitimate')}.", ""]

out += ["## Table 7. Probe (attacker's identifier reformatted; 2,645 attacked episodes) and analysis without user task 15", "",
        "| Arm | Probe: successful attacks | Primary without user task 15: attacks; all tasks | Second population without user task 15: attacks; all tasks |", "|---|---|---|---|"]
for a in ARMS:
    w1, w2 = R["populations"]["primary_S1"]["without_user_task_15"][a], R["populations"]["dev2"]["without_user_task_15"][a]
    out.append(f"| {NAME[a]} | {R['probe_reformatted_identifier']['arms'][a]['attacks']} | {w1['attacks']}; {n(w1['all_tasks'])} of {n(w1['n'])} | {w2['attacks']}; {n(w2['all_tasks'])} of {n(w2['n'])} |")
out += ["", "The analysis without user task 15 is a sensitivity analysis only; every comparison keeps the task.", ""]

for pk, title in (POPS[0], POPS[2]):
    P = R["populations"][pk]
    users = list(P["completion_by_user_task"]["GV"])
    sel = ["B0", "REM10", "A2", "PG", "G3", "GV", "HV", "NP01"]
    out += [f"## Table 8{'a' if pk == 'primary_S1' else 'b'}. Completed episodes by user task, {title}", "", "| User task | Episodes | " + " | ".join(a for a in sel) + " |", "|---|---|" + "---|" * len(sel)]
    for u in users:
        out.append(f"| {u.split('_')[-1]} | {P['completion_by_user_task']['GV'][u][1]} | " + " | ".join(str(P["completion_by_user_task"][a][u][0]) for a in sel) + " |")
    out.append("")
    out += [f"Successful attacks by user task ({title}): " + "; ".join(f"{a}: " + (", ".join(f"task {u.split('_')[-1]}: {v}" for u, v in P['attacks_by_user_task'][a].items() if v) or "none") for a in ["REM10", "REM11", "A2", "PG", "G3", "GV", "HV", "NP05", "CRC05", "GB"]), ""]

dg = R["diagnostics"]
out += ["## Table 9. Estimators on held-out S1 predictions (pooled over the nine held-out attacker objectives)", "",
        "| Estimator | Steps | n | Attack-labelled | ROC-AUC | Average precision | Brier | Log loss | ECE (10 bins) |", "|---|---|---|---|---|---|---|---|---|"]
f3 = lambda x: "n/a" if x is None else f"{x:.3f}"
for est, subs in dg["estimators_heldout_S1_pooled"].items():
    for sub, m in subs.items():
        out.append(f"| {est.replace('_', ' ')} | {sub.replace('_', ' ')} | {n(m['n'])} | {m['positives']} | {f3(m.get('roc_auc'))} | {f3(m.get('average_precision'))} | {f3(m.get('brier'))} | {f3(m.get('log_loss'))} | {f3(m.get('ece_10_bins'))} |")
out += ["", "\"Residual restricted steps\" are calls to restricted tools whose authority is established and that are not denied, by the offline evidence: the calls that reach the rule. "
        "These metrics describe the estimator; they are not authorization guarantees.", ""]

out += ["## Table 10. What each calibrated cutoff would release if it decided alone, per held-out attacker objective (not an arm)", "",
        "| Held-out objective | Attack-labelled steps | NP 0.05: released (share) | NP 0.01: released (share) | CRC 0.05: released (share) | CRC 0.01: released (share) | Legitimate restricted steps | NP 0.05 / NP 0.01 / CRC 0.05 / CRC 0.01: released |", "|---|---|---|---|---|---|---|---|"]
tot = {k: 0 for k in ("np_0.05", "np_0.01", "crc_0.05", "crc_0.01")}
ta = tl = 0
for fold, row in sorted(dg["cutoffs_alone_per_heldout_objective"].items(), key=lambda kv: int(kv[0].split("_")[-1])):
    a_, l_ = row["attack_labelled_steps"], row["legitimate_restricted_steps"]
    ta += a_
    tl += l_
    cells = []
    for k in tot:
        v = row[k]["attack_steps_below_cutoff"]
        tot[k] += v
        cells.append(f"{v} ({pct(v, a_)})")
    out.append(f"| {fold.split('_')[-1]} | {a_} | " + " | ".join(cells) + f" | {l_} | " + " / ".join(str(row[k]["legitimate_restricted_steps_below_cutoff"]) for k in tot) + " |")
out.append(f"| all | {ta} | " + " | ".join(f"{tot[k]} ({pct(tot[k], ta)})" for k in tot) + f" | {tl} | |")
over = {k: sum(1 for row in dg["cutoffs_alone_per_heldout_objective"].values() if row[k]["attack_steps_below_cutoff"] / max(1, row["attack_labelled_steps"]) > float(k.split("_")[1])) for k in tot}
out += ["", f"Held-out objectives (of 9) in which the share of attack-labelled steps below the cutoff exceeds the nominal level: {over}. The nominal levels are not guaranteed for these data (protocol, Section 6).", ""]

cells = FS["cells"]
import collections
gbc = collections.Counter((c["gb"]["max_depth"], c["gb"]["n_estimators"]) for c in cells)
out += ["## Table 11. Fitted quantities (152 cells)", "",
        f"- NP: left-out attack-labelled steps per cell {min(c['np']['n_left_out'] for c in cells)} to {max(c['np']['n_left_out'] for c in cells)}; infeasible calibrations: "
        f"{sum(1 for c in cells for a in c['np']['cut'].values() if not a['feasible'])}.",
        f"- CRC: calibration episodes per cell {min(c['crc']['n_units'] for c in cells)} to {max(c['crc']['n_units'] for c in cells)}; infeasible calibrations: "
        f"{sum(1 for c in cells for a in c['crc']['cut'].values() if not a['feasible'])}.",
        "- Gradient boosting, selected configuration (max depth, trees): " + "; ".join(f"({d}, {t}): {v} cells" for (d, t), v in sorted(gbc.items(), key=lambda kv: -kv[1])) +
        f"; leaves per model {min(c['gb']['n_leaves_total'] for c in cells)} to {max(c['gb']['n_leaves_total'] for c in cells)}. The ridge estimator has 9 coefficients, an intercept and 2 calibration parameters.", ""]

eq = R["equivalence_HVx_vs_stored_HV"]
out += ["## Table 12. Execution record", "",
        f"- New arms: {n(R['replays_new_arms'])} replays, {R['replay_errors_new_arms']} replay errors. Section 11 arms: {n(R11['replays'])} replays, {R11['replay_errors']} errors.",
        f"- Equivalence of the rebuilt HV rule with the stored HV arm: {n(eq['episodes_compared'])} replays compared, {eq['outcome_differences']} outcome differences, {eq['release_sequence_differences']} release-sequence differences.", ""]

P11 = R11["populations"]
par = R11["cedar_parity_GVc_vs_GV"]
out += ["## Table 13. Section 11 addendum: Cedar front (GVc) and provenance rule (GVp)", "",
        "| Arm | Primary: attacks / 2,979 | Primary: benign / 334 | Primary: all tasks / 3,313 | Primary: legitimate calls released / 178 | Second: attacks / 2,065 | Second: benign / 48 | Second: all tasks / 2,113 | Probe: attacks | Fixtures: legitimate / unsafe / pairs correct |",
        "|---|---|---|---|---|---|---|---|---|---|"]
for a in ["GV", "HV", "GVc", "GVp", "G3", "PG"]:
    p, d2 = P11["primary_S1"]["arms"][a], P11["dev2"]["arms"][a]
    if a in R11["fixtures"]:
        f = R11["fixtures"][a]
        fxs = f"{f['legitimate_released']} / {f['unsafe_released']} / {f['pairs_correct']}"
        pr = R11["probe_reformatted_identifier"][a]
    else:
        fxs = f"{sum(fx[s][a]['legitimate_released'] for s in fx)} / {sum(fx[s][a]['unsafe_released'] for s in fx)} / {sum(fx[s][a]['pairs_correct'] for s in fx)}"
        pr = R["probe_reformatted_identifier"]["arms"][a]["attacks"]
    out.append(f"| {NAME[a]} | {p['attacks_successful']} | {p['benign_completed']} | {n(p['all_tasks_completed'])} | {p['legit_calls_released_benign']} | {d2['attacks_successful']} | {d2['benign_completed']} | {n(d2['all_tasks_completed'])} | {pr} | {fxs} |")
out += ["", f"**Cedar parity (GVc against GV).** {n(par['replays_compared'])} replays; {n(par['restricted_calls_compared'])} restricted calls decided by Cedar ({par['cedar_decisions']}); "
        f"{par['release_decision_differences']} release-decision differences; {par['outcome_differences']} outcome differences; {par['cedar_errors']} authorizer errors. "
        f"Decision time of a restricted call under GVc: median {par['decision_ms_median_restricted_calls_GVc']:.2f} ms, 95th percentile {par['decision_ms_p95_restricted_calls_GVc']:.2f} ms.", "",
        "| Contrast | Population | All-task completion | Benign task completion | Attack success | Tasks gained / lost |", "|---|---|---|---|---|---|"]
for key in ("GVp minus GV", "GVp minus HV", "GVp minus G3", "GVp minus PG", "GVc minus GV"):
    for pk, title in (("primary_S1", "primary"), ("dev2", "second")):
        c = P11[pk]["contrasts"][key]
        out.append(f"| {key.replace(' minus ', ' − ')} | {title} | {iv(c['task_completion_all'])} | {iv(c['task_completion_benign'])} | {iv(c['attack_success'])} | {c['tasks_gained_lost'][0]} / {c['tasks_gained_lost'][1]} |")
for pk, title in (("primary_S1", "primary"), ("dev2", "second")):
    s = P11[pk]["restricted_calls_by_source"]["GVp"]
    out += ["", f"GVp, restricted calls by deciding stage ({title}): " + "; ".join(f"{k}: {v}" for k, v in sorted(s.items()))]
    cu = P11[pk]["completion_by_user_task"]
    diff = {u.split('_')[-1]: cu["GVp"][u][0] - cu["GV"][u][0] for u in cu["GV"] if cu["GVp"][u][0] != cu["GV"][u][0]}
    out += [f"GVp minus GV, completed episodes by user task ({title}): {diff if diff else 'no difference'}"]
out.append("")
(D / "03_RESULTS_TABLES.md").write_text("\n".join(out), encoding="utf-8")
print("written", len(out), "lines")
