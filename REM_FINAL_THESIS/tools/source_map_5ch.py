def evidence(new):
    n = new.split('-')[0].split(',')[0].strip()
    if n.startswith('1.'):
        return 'Framing text; no result of its own (points to Chapters 3–5).'
    if n.startswith('2.'):
        return 'Record-level literature evidence (metadata/abstract; no full text verified). See REFERENCES_AUDIT.md.'
    if n == '3.16' or n.startswith('3.16.'):
        return 'Implemented; verified by the automated test suite (217 tests pass incl. 12 live-integration tests).'
    if n == '3.17':
        return 'Implemented; tested with scripted test agents only. NOT executed with a language model.'
    if n.startswith('3.'):
        return 'Specification. Design values declared exploratory (pilot_e0_exploratory), not supervisor-approved.'
    if n in ('4.12',):
        return 'NOT EXECUTED. No live result exists.'
    if n == '4.13':
        return 'Methodological comparison only; no live numbers.'
    if n in ('4.14', '4.15', '4.16', '4.17'):
        return 'Interpretation of exploratory recorded-trace results; comparison with prior work at record level.'
    if n.startswith('4.'):
        return 'Exploratory results on recorded traces (offline / observe-only / NO-ADAPT replay). Re-execution: 0 analytical differences.'
    if n.startswith('5.'):
        return 'Conclusions limited to the exploratory evidence of Chapter 4.'
    return ''


