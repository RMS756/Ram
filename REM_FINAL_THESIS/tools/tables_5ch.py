"""Export every captioned table of the five-chapter thesis to CSV.

Reads final_five_chapters/src/*.md (the exact text built into the DOCX/PDF) and writes
final_five_chapters/tables/Table_<ch>_<n>.csv plus tables/INDEX.md. Cell text is copied as written
(Markdown emphasis markers removed); no value is recomputed.
"""
import csv
import glob
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
FF = os.path.join(HERE, '..', 'final_five_chapters')
OUT = os.path.join(FF, 'tables')
os.makedirs(OUT, exist_ok=True)
for f in glob.glob(os.path.join(OUT, 'Table_*.csv')):
    os.remove(f)

CAP = re.compile(r'^\*\*Table (\d+)\.(\d+)\.\s*(.*?)\*\*\s*(.*)$')


def clean(c):
    c = c.strip()
    c = re.sub(r'\*\*(.*?)\*\*', r'\1', c)
    c = re.sub(r'(?<![\w*])\*(?!\s)(.*?)(?<!\s)\*(?![\w*])', r'\1', c)
    c = re.sub(r'~(.*?)~', r'_\1', c)
    return c.replace('\\|', '|')


def split_row(line):
    line = line.strip()
    if line.startswith('|'):
        line = line[1:]
    if line.endswith('|'):
        line = line[:-1]
    return [clean(x) for x in re.split(r'(?<!\\)\|', line)]


index = []
for src in sorted(glob.glob(os.path.join(FF, 'src', '*.md'))):
    lines = open(src, encoding='utf-8').read().split('\n')
    i = 0
    while i < len(lines):
        m = CAP.match(lines[i])
        if not m:
            i += 1
            continue
        j = i + 1
        while j < len(lines) and not lines[j].strip():
            j += 1
        rows = []
        while j < len(lines) and lines[j].startswith('|'):
            if not re.match(r'^\|[\s:|-]+\|?\s*$', lines[j]):
                rows.append(split_row(lines[j]))
            j += 1
        if rows:
            name = f'Table_{m.group(1)}_{int(m.group(2)):02d}.csv'
            with open(os.path.join(OUT, name), 'w', newline='', encoding='utf-8') as fh:
                csv.writer(fh).writerows(rows)
            cap = clean(m.group(3) + (' ' + m.group(4).strip() if m.group(4).strip() else ''))
            index.append((int(m.group(1)), int(m.group(2)), name, cap.replace('|', '/'), len(rows) - 1, os.path.basename(src)))
        i = j

index.sort()
with open(os.path.join(OUT, 'INDEX.md'), 'w', encoding='utf-8') as fh:
    fh.write('# Tables of the five-chapter thesis (CSV exports)\n\n'
             'Generated by `REM_FINAL_THESIS/tools/tables_5ch.py` from `final_five_chapters/src/*.md`, '
             'the text built into `REM_THESIS_5CH_FINAL.docx`. Values are copied as printed in the thesis; '
             'none is recomputed. Result values originate from `results/pilot_R2/` and `results/pilot_R4/` '
             'as cited in each table. **All results are exploratory; no table contains a live-agent result.**\n\n'
             '| Table | File | Caption | Data rows | Chapter file |\n|---|---|---|---:|---|\n')
    for ch, n, name, cap, nrows, srcf in index:
        fh.write(f'| {ch}.{n} | `{name}` | {cap} | {nrows} | {srcf} |\n')
print('tables exported:', len(index))
